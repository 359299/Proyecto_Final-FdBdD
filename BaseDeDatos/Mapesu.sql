-- Notas:
--  * Productos, empleados, clientes y proveedores se "eliminan" con ACTIVO = 0 (conserva el historial).
--  * Categorias se borran de verdad (falla si tienen productos, y la app avisa).
--  * Cada producto debe tener un proveedor (PRODUCTOS.ID_PROVEEDOR NOT NULL).
--  * Si ya tienes la base creada, NO corras este script: usa Migracion_Proveedores.sql

-- 1. CATEGORIAS
CREATE TABLE CATEGORIAS (
    ID_CATEGORIA NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE       VARCHAR2(60)  NOT NULL,
    DESCRIPCION  VARCHAR2(255),
    CONSTRAINT PK_CATEGORIAS PRIMARY KEY (ID_CATEGORIA),
    CONSTRAINT UQ_CATEGORIAS_NOMBRE UNIQUE (NOMBRE)
);

-- 1.1 PROVEEDORES
CREATE TABLE PROVEEDORES (
    ID_PROVEEDOR NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE       VARCHAR2(100) NOT NULL,
    TELEFONO     VARCHAR2(20),
    CORREO       VARCHAR2(100),
    DIRECCION    VARCHAR2(200),
    ACTIVO       NUMBER(1)     DEFAULT 1 NOT NULL,
    CONSTRAINT PK_PROVEEDORES PRIMARY KEY (ID_PROVEEDOR),
    CONSTRAINT UQ_PROVEEDORES_NOMBRE UNIQUE (NOMBRE),
    CONSTRAINT CK_PROVEEDORES_ACTIVO CHECK (ACTIVO IN (0, 1))
);

-- 2. PRODUCTOS
CREATE TABLE PRODUCTOS (
    ID_PRODUCTO  NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE       VARCHAR2(100) NOT NULL,
    PRECIO_VENTA NUMBER(10,2)  NOT NULL,
    STOCK        NUMBER(10)    DEFAULT 0 NOT NULL,
    ACTIVO       NUMBER(1)     DEFAULT 1 NOT NULL,
    ID_CATEGORIA NUMBER(10)    NOT NULL,
    ID_PROVEEDOR NUMBER(10)    NOT NULL,
    CONSTRAINT PK_PRODUCTOS PRIMARY KEY (ID_PRODUCTO),
    CONSTRAINT FK_PRODUCTOS_CATEGORIAS FOREIGN KEY (ID_CATEGORIA)
        REFERENCES CATEGORIAS (ID_CATEGORIA),
    CONSTRAINT FK_PRODUCTOS_PROVEEDORES FOREIGN KEY (ID_PROVEEDOR)
        REFERENCES PROVEEDORES (ID_PROVEEDOR),
    CONSTRAINT CK_PRODUCTOS_PRECIO CHECK (PRECIO_VENTA >= 0),
    CONSTRAINT CK_PRODUCTOS_STOCK CHECK (STOCK >= 0),
    CONSTRAINT CK_PRODUCTOS_ACTIVO CHECK (ACTIVO IN (0, 1))
);

-- 3. CLIENTES (ID_CLIENTE opcional en VENTAS = venta de contado)
CREATE TABLE CLIENTES (
    ID_CLIENTE NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE     VARCHAR2(100) NOT NULL,
    TELEFONO   VARCHAR2(20),
    DIRECCION  VARCHAR2(200),
    ACTIVO     NUMBER(1)     DEFAULT 1 NOT NULL,
    CONSTRAINT PK_CLIENTES PRIMARY KEY (ID_CLIENTE),
    CONSTRAINT CK_CLIENTES_ACTIVO CHECK (ACTIVO IN (0, 1))
);

-- 4. EMPLEADOS
CREATE TABLE EMPLEADOS (
    ID_EMPLEADO NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE      VARCHAR2(100) NOT NULL,
    PUESTO      VARCHAR2(40)  DEFAULT 'CAJERO' NOT NULL,
    TELEFONO    VARCHAR2(20),
    ACTIVO      NUMBER(1)     DEFAULT 1 NOT NULL,
    CONSTRAINT PK_EMPLEADOS PRIMARY KEY (ID_EMPLEADO),
    CONSTRAINT CK_EMPLEADOS_ACTIVO CHECK (ACTIVO IN (0, 1))
);

-- 5. VENTAS (cabecera de ticket)
CREATE TABLE VENTAS (
    ID_VENTA    NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY,
    FECHA_HORA  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    TOTAL       NUMBER(12,2)  DEFAULT 0 NOT NULL,
    ID_CLIENTE  NUMBER(10),
    ID_EMPLEADO NUMBER(10)    NOT NULL,
    CONSTRAINT PK_VENTAS PRIMARY KEY (ID_VENTA),
    CONSTRAINT FK_VENTAS_CLIENTES FOREIGN KEY (ID_CLIENTE)
        REFERENCES CLIENTES (ID_CLIENTE),
    CONSTRAINT FK_VENTAS_EMPLEADOS FOREIGN KEY (ID_EMPLEADO)
        REFERENCES EMPLEADOS (ID_EMPLEADO),
    CONSTRAINT CK_VENTAS_TOTAL CHECK (TOTAL >= 0)
);

-- 6. DETALLE_VENTAS (productos por venta)
CREATE TABLE DETALLE_VENTAS (
    ID_DETALLE      NUMBER(10)   GENERATED BY DEFAULT AS IDENTITY,
    ID_VENTA        NUMBER(10)   NOT NULL,
    ID_PRODUCTO     NUMBER(10)   NOT NULL,
    CANTIDAD        NUMBER(10)   NOT NULL,
    PRECIO_UNITARIO NUMBER(10,2) NOT NULL,
    SUBTOTAL        NUMBER(12,2) NOT NULL,
    CONSTRAINT PK_DETALLE_VENTAS PRIMARY KEY (ID_DETALLE),
    CONSTRAINT FK_DETALLE_VENTAS_VENTAS FOREIGN KEY (ID_VENTA)
        REFERENCES VENTAS (ID_VENTA),
    CONSTRAINT FK_DETALLE_VENTAS_PRODUCTOS FOREIGN KEY (ID_PRODUCTO)
        REFERENCES PRODUCTOS (ID_PRODUCTO),
    CONSTRAINT CK_DETALLE_CANTIDAD CHECK (CANTIDAD > 0),
    CONSTRAINT CK_DETALLE_PRECIO CHECK (PRECIO_UNITARIO >= 0),
    CONSTRAINT CK_DETALLE_SUBTOTAL CHECK (SUBTOTAL >= 0)
);

-- INDICES SOBRE LLAVES FORANEAS
CREATE INDEX IX_PRODUCTOS_CATEGORIA ON PRODUCTOS (ID_CATEGORIA);
CREATE INDEX IX_PRODUCTOS_PROVEEDOR ON PRODUCTOS (ID_PROVEEDOR);
CREATE INDEX IX_VENTAS_CLIENTE      ON VENTAS (ID_CLIENTE);
CREATE INDEX IX_VENTAS_EMPLEADO     ON VENTAS (ID_EMPLEADO);
CREATE INDEX IX_DETALLE_VENTA       ON DETALLE_VENTAS (ID_VENTA);
CREATE INDEX IX_DETALLE_PRODUCTO    ON DETALLE_VENTAS (ID_PRODUCTO);